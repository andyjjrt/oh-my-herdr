// Copy the host-neutral core and shared skills into the Claude Code plugin directory, and build the
// plugin's self-contained type contract. Claude Code copies only the plugin's source directory on
// install, so claudecode/ must contain real files. The copies are generated and committed; edit
// /core and /skills, then run:
//
//   bun scripts/sync.ts
//   bun scripts/sync.ts --check
//
// --check exits 1 and names every missing, stale or different file.

import { chmodSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const GENERATED = "README.md"
const SOURCES = [
  { name: "core", source: join(ROOT, "core"), target: join(ROOT, "claudecode", "core") },
  { name: "skills", source: join(ROOT, "skills"), target: join(ROOT, "claudecode", "skills") },
] as const
const TYPES_SOURCE = join(ROOT, "core", "types.ts")
const TYPES_TARGET = join(ROOT, "claudecode", "types", "index.d.ts")
function generatedHeader(rel: string): string {
  return [
    `// GENERATED FILE - do not edit; source: /core/${rel}`,
    "// Regenerate with: bun scripts/sync.ts",
    "// Claude Code needs real files in the plugin; this header also keeps the generated copy",
    "// distinct from the source in Git rename detection, so the source keeps its history.",
    "",
  ].join("\n")
}

const AUGMENTATION = `// Claude Code's $.state contract. The domain types above are copied from core/types.ts; this
// file is self-contained because the Claude plugin manifest validator rejects imports in a types
// contract. Edit core/types.ts, then run bun scripts/sync.ts.

declare module 'claude-code' {
  interface PluginState {
    'oh-my-herdr': {
      run: Shaped<OmhRunView | null>
      workers: Shaped<Record<string, OmhWorker>>
      quota: Shaped<Record<string, OmhQuota>>
      continueCount: number
      /** Wake-ups not yet sent to the lead, and the last wave state it was told about. Kept here so a reload loses neither. */
      wake: Shaped<OmhWake>
      /** The session's run binding: its files win over .omh/current-run, and its root over this checkout. */
      bound: Shaped<OmhBoundRun | { run: null } | null>
    }
  }
}
`

type Change = {
  kind: "write" | "update" | "delete"
  path: string
  source?: string
  target: string
  content?: string
}

function note(name: string): string {
  return `<!-- generated by scripts/sync.ts from /${name} - edit /${name}, not this copy -->\n`
}

function expectedTypes(): string {
  return `${readFileSync(TYPES_SOURCE, "utf8").replace(/\s+$/, "")}\n\n${AUGMENTATION}`
}

function isExcluded(name: string, rel: string): boolean {
  if (name === "node_modules" || name === ".DS_Store") return true
  return rel === "tests" || rel.startsWith("tests/")
}

function walk(root: string, prefix = ""): string[] {
  if (!existsSync(root)) return []
  const out: string[] = []
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name
    if (isExcluded(entry.name, rel)) continue
    const absolute = join(root, entry.name)
    if (entry.isDirectory()) out.push(...walk(absolute, rel))
    else if (entry.isFile()) out.push(rel)
  }
  return out
}

function same(source: string, target: string): boolean {
  if (!existsSync(target)) return false
  try {
    return readFileSync(source).equals(readFileSync(target))
  } catch {
    return false
  }
}

function sourceChanges(item: (typeof SOURCES)[number]): Change[] {
  const changes: Change[] = []
  const sourceFiles = new Set(walk(item.source))
  for (const rel of sourceFiles) {
    const source = join(item.source, rel)
    const target = join(item.target, rel)
    if (item.name === "core" && rel.endsWith(".ts")) {
      const content = generatedHeader(rel) + readFileSync(source, "utf8")
      let current = ""
      try {
        current = readFileSync(target, "utf8")
      } catch {
        current = ""
      }
      if (current !== content) {
        changes.push({ kind: existsSync(target) ? "update" : "write", path: `core/${rel}`, target, content })
      }
      continue
    }
    if (!same(source, target)) {
      changes.push({ kind: existsSync(target) ? "update" : "write", path: `${item.name}/${rel}`, source, target })
    }
  }
  const notePath = join(item.target, GENERATED)
  const noteContent = note(item.name)
  let current = ""
  try {
    current = readFileSync(notePath, "utf8")
  } catch {
    current = ""
  }
  if (current !== noteContent) {
    changes.push({ kind: existsSync(notePath) ? "update" : "write", path: `${item.name}/${GENERATED}`, target: notePath, content: noteContent })
  }
  for (const rel of walk(item.target)) {
    if (rel === GENERATED || sourceFiles.has(rel)) continue
    changes.push({ kind: "delete", path: `${item.name}/${rel}`, target: join(item.target, rel) })
  }
  return changes
}

function typeChanges(): Change[] {
  if (!existsSync(TYPES_SOURCE)) return []
  const expected = expectedTypes()
  let current = ""
  try {
    current = readFileSync(TYPES_TARGET, "utf8")
  } catch {
    current = ""
  }
  return current === expected
    ? []
    : [{ kind: existsSync(TYPES_TARGET) ? "update" : "write", path: "types/index.d.ts", target: TYPES_TARGET, content: expected }]
}

function apply(changes: Change[]): void {
  for (const change of changes) {
    if (change.kind === "delete") {
      rmSync(change.target, { force: true })
      continue
    }
    mkdirSync(dirname(change.target), { recursive: true })
    if (change.content !== undefined) {
      writeFileSync(change.target, change.content)
      continue
    }
    if (change.source === undefined) continue
    writeFileSync(change.target, readFileSync(change.source))
    chmodSync(change.target, statSync(change.source).mode & 0o777)
  }
}

const check = process.argv.includes("--check")
const changes = [...SOURCES.flatMap(sourceChanges), ...typeChanges()]

if (check) {
  if (changes.length === 0) {
    console.log("sync: clean")
    process.exit(0)
  }
  for (const change of changes) console.log(`${change.kind} ${change.path}`)
  console.error(`sync: ${changes.length} file(s) differ; run bun scripts/sync.ts`)
  process.exit(1)
}

apply(changes)
for (const change of changes) console.log(`${change.kind} ${change.path}`)
console.log(changes.length === 0 ? "sync: clean" : `sync: ${changes.length} change(s)`)
